my_tuple = (1, 2, 3, 4, 5)
print(my_tuple[0])  # Accessing the first element
print(my_tuple[1:4])  # Slicing the tuple
print(len(my_tuple))  # Getting the length of the tuple
print(my_tuple + (6, 7))  # Concatenating tuples
print(my_tuple * 2)  # Repeating the tuple

for item in my_tuple:
    print("item1:" + str(item))  # Iterating through the tuple