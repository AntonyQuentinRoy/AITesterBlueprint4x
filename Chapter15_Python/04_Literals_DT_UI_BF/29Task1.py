# Task for the Today
# Take a 3 input from the user
# perform the sum, sub, mul and div

input1 = int(input("Enter first number: "))
input2 = int(input("Enter second number: "))
input3 = int(input("Enter third number: "))

#SUM
sum_result = input1 + input2 + input3
print("The sum of the three numbers is: ", sum_result)

#SUB
sub_result = input1 - input2 - input3
print("The subtraction of the three numbers is: ", sub_result)

#MUL
mul_result = input1 * input2 * input3
print("The multiplication of the three numbers is: ", mul_result)

#DIV
div_result = input1 / input2 / input3
print("The division of the three numbers is: ", div_result)